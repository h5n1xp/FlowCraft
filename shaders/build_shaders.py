#!/usr/bin/env python3
"""Compiles the GLSL shaders in this folder to SPIR-V (glslc) and Metal (SDL_shadercross,
SPIR-V -> MSL), and writes ../FlowCraft/generated/ShaderBlobs.h with both embedded as
byte arrays. The generated header is committed so that building FlowCraft needs no
shader tools; re-run this script (needs `glslc` and `shadercross` on PATH, or set
SHADERCROSS=/path/to/shadercross) after editing any *.glsl file.
"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "FlowCraft", "generated", "ShaderBlobs.h")
SHADERCROSS = os.environ.get("SHADERCROSS", "shadercross")

# name, file, glslc stage, shadercross stage
SHADERS = [
    ("MeshVert", "mesh.vert.glsl", "vert", "vertex"),
    ("MeshFrag", "mesh.frag.glsl", "frag", "fragment"),
    ("OverlayVert", "overlay.vert.glsl", "vert", "vertex"),
    ("OverlayFrag", "overlay.frag.glsl", "frag", "fragment"),
    ("OverlayTransparentFrag", "overlay_transparent.frag.glsl", "frag", "fragment"),
    ("LbmStepComp", "lbm_step.comp.glsl", "comp", "compute"),
]

def array(name, data):
    body = ",".join(str(b) for b in data)
    return f"inline constexpr unsigned char {name}[] = {{{body}}};\ninline constexpr unsigned long {name}Size = {len(data)};\n"

out = ["// GENERATED by shaders/build_shaders.py — do not edit. Run that script after changing a *.glsl file.\n",
       "#pragma once\n\n"]
with tempfile.TemporaryDirectory() as tmp:
    for name, src, stage, sc_stage in SHADERS:
        spv = os.path.join(tmp, name + ".spv")
        msl = os.path.join(tmp, name + ".metal")
        subprocess.check_call(["glslc", f"-fshader-stage={stage}", "-O", os.path.join(HERE, src), "-o", spv])
        subprocess.check_call([SHADERCROSS, spv, "-s", "SPIRV", "-d", "MSL", "-t", sc_stage, "-e", "main", "-o", msl])
        out.append(array(name + "_SPIRV", open(spv, "rb").read()))
        # MSL is source text — embed NUL-terminated so it can also be treated as a C string.
        out.append(array(name + "_MSL", open(msl, "rb").read() + b"\0"))
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("".join(out))
print("wrote", os.path.normpath(OUT))
