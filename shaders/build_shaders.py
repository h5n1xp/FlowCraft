#!/usr/bin/env python3
"""Compiles the GLSL shaders in this folder to SPIR-V (glslc) and Metal (spirv-cross,
with SDL_GPU's Metal buffer binding order applied from SPIR-V reflection), and writes
../FlowCraft/generated/ShaderBlobs.h with both embedded as byte arrays.
The generated header is committed so that building FlowCraft needs no shader tools;
re-run this script (needs `glslc` and `spirv-cross` on PATH) after editing any *.glsl file.
"""
import json, os, re, subprocess, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "FlowCraft", "generated", "ShaderBlobs.h")

# name, file, glslc stage
SHADERS = [
    ("MeshVert", "mesh.vert.glsl", "vert"),
    ("MeshFrag", "mesh.frag.glsl", "frag"),
    ("OverlayVert", "overlay.vert.glsl", "vert"),
    ("OverlayFrag", "overlay.frag.glsl", "frag"),
    ("OverlayTransparentFrag", "overlay_transparent.frag.glsl", "frag"),
    ("LbmStepComp", "lbm_step.comp.glsl", "comp"),
    ("PanelEvalComp", "panel_eval.comp.glsl", "comp"),
]

def array(name, data):
    body = ",".join(str(b) for b in data)
    return f"inline constexpr unsigned char {name}[] = {{{body}}};\ninline constexpr unsigned long {name}Size = {len(data)};\n"

def compile_to_sdl_gpu_msl(spv_path):
    """Translates SPIR-V to MSL via spirv-cross and remaps [[buffer(N)]] attributes
    on main0(...) to SDL_GPU's Metal binding order:
      1. uniform buffers (sorted by binding)
      2. read-only storage buffers (set=0, sorted by binding)
      3. read-write storage buffers (set=1, sorted by binding)
    """
    refl_json = subprocess.check_output(["spirv-cross", spv_path, "--reflect"]).decode("utf-8")
    refl = json.loads(refl_json)
    msl = subprocess.check_output(["spirv-cross", spv_path, "--msl"]).decode("utf-8")

    ubos = refl.get("ubos", [])
    ssbos = refl.get("ssbos", [])
    num_ubos = len(ubos)
    num_ro_ssbos = sum(1 for b in ssbos if b.get("set", 0) == 0)

    # Map struct type name (e.g. "_155") -> SDL_GPU Metal buffer slot
    type_to_slot = {}
    for u in ubos:
        type_to_slot[u["type"]] = u.get("binding", 0)
    for b in ssbos:
        if b.get("set", 0) == 0:
            type_to_slot[b["type"]] = num_ubos + b.get("binding", 0)
        else:
            type_to_slot[b["type"]] = num_ubos + num_ro_ssbos + b.get("binding", 0)

    def remap_param(m):
        prefix, tname, rest = m.group(1), m.group(2), m.group(3)
        if tname in type_to_slot:
            return f"{prefix}{tname}{rest}[[buffer({type_to_slot[tname]})]]"
        return m.group(0)

    msl = re.sub(r"((?:constant|device)\s+)([A-Za-z0-9_]+)(\s*&\s*[A-Za-z0-9_]+\s*)\[\[buffer\(\d+\)\]\]",
                 remap_param, msl)
    return msl.encode("utf-8")

out = ["// GENERATED by shaders/build_shaders.py — do not edit. Run that script after changing a *.glsl file.\n",
       "#pragma once\n\n"]
with tempfile.TemporaryDirectory() as tmp:
    for name, src, stage in SHADERS:
        spv = os.path.join(tmp, name + ".spv")
        subprocess.check_call(["glslc", f"-fshader-stage={stage}", "-O", os.path.join(HERE, src), "-o", spv])
        msl_bytes = compile_to_sdl_gpu_msl(spv)
        out.append(array(name + "_SPIRV", open(spv, "rb").read()))
        # MSL is source text — embed NUL-terminated so it can also be treated as a C string.
        out.append(array(name + "_MSL", msl_bytes + b"\0"))
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("".join(out))
print("wrote", os.path.normpath(OUT))
